"""Build a Font Awesome 6.0.0 subset for the icons the site actually uses.

usage: python -I fa_subset.py <fa-dl dir> <site src dir> <out font dir> <out css file>
"""
import glob
import os
import re
import sys

from fontTools import subset

dl, src, out_dir, out_css = sys.argv[1:5]

# 1. icons used: every fa-* token inside a class attribute that also has fas/fab
used = {}  # name -> set of styles
for path in glob.glob(os.path.join(src, "**", "*.html"), recursive=True):
    if "src-backup" in path:
        continue
    html = open(path, encoding="utf-8").read()
    for cls in re.findall(r'class="([^"]*)"', html):
        toks = cls.split()
        style = "fab" if ("fab" in toks or "fa-brands" in toks) else (
            "fas" if ("fas" in toks or "fa-solid" in toks or "fa" in toks) else None)
        if not style:
            continue
        for t in toks:
            if t.startswith("fa-") and t not in ("fa-solid", "fa-brands", "fa-regular"):
                used.setdefault(t[3:], set()).add(style)

# 2. codepoints from all.css: brands section starts at the Brands @font-face
css = open(os.path.join(dl, "all.css"), encoding="utf-8").read()
cut = css.index("font-family: 'Font Awesome 6 Brands'")
rule = re.compile(r'\.fa-([a-z0-9-]+):{1,2}before\s*\{\s*content:\s*"\\([0-9a-f]+)";\s*\}')
main = {m.group(1): m.group(2) for m in rule.finditer(css[:cut])}
brands = {m.group(1): m.group(2) for m in rule.finditer(css[cut:])}

solid_cp, brand_cp, lines, missing = set(), set(), [], []
for name in sorted(used):
    styles = used[name]
    table = brands if styles == {"fab"} else main
    if name not in table:
        missing.append(f"{name} ({','.join(sorted(styles))})")
        continue
    cp = table[name]
    (brand_cp if table is brands else solid_cp).add(int(cp, 16))
    lines.append(f'.fa-{name}::before {{ content: "\\{cp}"; }}')
if missing:
    sys.exit("icons not found in FA 6.0.0: " + ", ".join(missing))

# 3. subset the two webfonts to exactly those glyphs
os.makedirs(out_dir, exist_ok=True)
for font, cps, name in (("fa-solid-900.ttf", solid_cp, "fa-solid-900-subset.woff2"),
                        ("fa-brands-400.ttf", brand_cp, "fa-brands-400-subset.woff2")):
    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = []
    f = subset.load_font(os.path.join(dl, font), opts)
    s = subset.Subsetter(opts)
    s.populate(unicodes=cps)
    s.subset(f)
    subset.save_font(f, os.path.join(out_dir, name), opts)

head = """
/* ==========================================================================
   Phase I — Font Awesome 6.0.0 subset (self-hosted)
   Generated by a subset script: only the {n} icons the HTML uses. The full
   CDN build was 244KB (CSS + 2 webfonts) at top fetch priority, competing
   with the hero image. ADDING A NEW ICON: it will render as an empty box
   until it is added here AND to the subset fonts in font/fontawesome/.
   Font Awesome Free 6.0.0 — Icons CC BY 4.0, Fonts SIL OFL 1.1, Code MIT.
   ========================================================================== */
@font-face {{
    font-family: 'Font Awesome 6 Free';
    font-style: normal;
    font-weight: 900;
    font-display: block;
    src: url("../font/fontawesome/fa-solid-900-subset.woff2") format("woff2");
}}
@font-face {{
    font-family: 'Font Awesome 6 Brands';
    font-style: normal;
    font-weight: 400;
    font-display: block;
    src: url("../font/fontawesome/fa-brands-400-subset.woff2") format("woff2");
}}
.fa, .fas, .fa-solid, .fab, .fa-brands {{
    -moz-osx-font-smoothing: grayscale;
    -webkit-font-smoothing: antialiased;
    display: inline-block;
    font-style: normal;
    font-variant: normal;
    line-height: 1;
    text-rendering: auto;
}}
.fa, .fas, .fa-solid {{ font-family: 'Font Awesome 6 Free'; font-weight: 900; }}
.fab, .fa-brands {{ font-family: 'Font Awesome 6 Brands'; font-weight: 400; }}
""".format(n=len(lines))

with open(out_css, "w", encoding="utf-8") as fh:
    fh.write(head + "\n".join(lines) + "\n")
print(f"{len(lines)} icons: {len(solid_cp)} solid glyphs, {len(brand_cp)} brand glyphs")
